"""Build the 2026-11-09 sea / land / air tri-modal dataset.

Three domains x 3 frames each, three modalities per frame
(visible / LWIR / radar range-Doppler), generated by the same offline simkit
pipeline that produced the v3 interference runs. Output:
    D:\\work\\多模态数据集生成\\dataest\\海陆空1109\\{air_plane,ground_vehicle,sea_ship}

What changed relative to the v3 runs
  * ground interference: the twelve grey box/primitive "clutter" stand-ins are
    replaced by three real vehicle OBJ instances (normal-looking cars / SUV /
    off-roader), each normalised to a plausible 2.2 m height and left
    label:false as hard negatives.
  * air infrared decoys: the two sphere flares become a six-round dispensed fan
    with per-round head radius and streak length. ecm.flare_mesh() gives every
    round a bright compact head plus a tapered trail; the same mesh feeds the
    numpy World and the Cycles frame, so all modalities stay registered.
  * the PLAN.md priority-list fixes are active through scene.load_config ->
    realism.apply(); this scene family additionally opts into output.jpeg.

Usage
    env\\Scripts\\python.exe tools\\build_sealandair_1109.py
    env\\Scripts\\python.exe tools\\build_sealandair_1109.py --skip-gen  # verify only
"""
import argparse
import copy
import json
import math
import os
import shutil
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SCENES = os.path.join(ROOT, "scenes")
PY = os.path.join(ROOT, "env", "Scripts", "python.exe")
DEFAULT_DEST = r"D:\work\多模态数据集生成\dataest\海陆空1109"
N_FRAMES = 3
SENSORS = "optical,ir,radar"

DOMAINS = [
    dict(key="air_plane", label="空", base="ds20_v3_air_plane.json"),
    dict(key="ground_vehicle", label="陆", base="ds20_v3_ground_vehicle.json"),
    dict(key="sea_ship", label="海", base="ds20_v3_sea_ship.json"),
]

# Ground interference is split into two physically different classes.
# motion_type="ground" is load-bearing: without it the seeker planner treats
# every non-primary object as a FORMATION member and drags it along with the
# target, which is exactly how a "static" barrier ended up moving.
# (name, model, pos, yaw, height, material)
STATIC_OBSTACLES = [
    ("barrier_static", "../assets/models/concrete_road_barrier.obj",
     [-35.0, 22.0, 0.0], 12.0, 0.9, "concrete"),
    ("fence_static", "../assets/models/modular_chainlink_fence.obj",
     [40.0, -8.0, 0.0], 90.0, 2.4, "metal_bare"),
    ("shrub_static", "../assets/models/shrub_01.obj",
     [-20.0, -40.0, 0.0], 0.0, 1.6, "foliage"),
    ("parked_car_static", "../assets/models/地面车辆/家用轿车.obj",
     [15.0, 38.0, 0.0], -20.0, 1.6, "painted_metal"),
]
# Only these may move: other traffic crossing the scene.
# (name, model, pos, velocity, height, material)
MOVING_VEHICLES = [
    ("moving_suv", "../assets/models/地面车辆/运动型多用途车.obj",
     [-34.0, 21.0, 0.0], [9.0, 3.0, 0.0], 2.0, "matte_paint"),
    ("moving_pickup", "../assets/models/地面车辆/皮卡.obj",
     [37.0, -16.0, 0.0], [-7.0, 4.0, 0.0], 1.9, "painted_metal"),
]


def jload(path):
    with open(path, "r", encoding="utf-8") as fh:
        return json.load(fh)


def jwrite(path, obj):
    with open(path, "w", encoding="utf-8") as fh:
        json.dump(obj, fh, ensure_ascii=False, indent=2)


def flare_fan(cfg):
    """Six rounds dispensed symmetrically below the aircraft's own axis.

    Three things were wrong with the previous fan and are fixed here:

    * The rounds were authored in world coordinates far from the aircraft and
      inherited its full 250 m/s velocity, so they flew alongside it instead of
      falling away. Here the mount points are in the aircraft BODY frame
      (body_to_world with the planner's frame-0 attitude): three evenly spaced
      stations aft along the fuselage, mirrored left/right, below the wing.
    * The ejection velocity is dominated by -Z (down) with only a few m/s of
      aft/outboard drift. It deliberately does NOT contain the aircraft's
      velocity, so each round separates downward from the aircraft frame by
      frame. An independent (pos + vel*t) trajectory is used on purpose: the
      optical manifest and the numpy World must agree exactly, and the Blender
      side extrapolates linearly rather than evaluating the ECM link model.
    * A round is a hand-sized pellet (0.18-0.26 m radius, 2.4-3.6 m trail),
      i.e. well under the ~17 m aircraft. The old 1 m head with a 22 m tail
      made every decoy larger than the target it was decoying.
    """
    import numpy as np
    from simkit import motion, plan as planlib

    primary = (cfg.get("objects") or [{}])[0]
    name = primary.get("name") or "fighter_01"
    state = next(iter(planlib.plan_frames(
        cfg, 1, int(cfg.get("seed", 0)), float(cfg["frames"]["dt"]))))
    pose = (state.get("poses") or {}).get(name) or {}
    p0 = np.asarray(pose.get("pos") or primary.get("pos") or [0, 0, 2500], float)
    # Use the HEADING axis only. Including the -27 deg dive pitch in the mount
    # rotation tilts an aft offset upwards, which put the "downward" rounds
    # above the aircraft. Vertical separation is applied in world -Z instead.
    R = np.asarray(motion.body_to_world(
        pose.get("yaw", 0.0), 0.0, 0.0), float)

    radii = (0.20, 0.22, 0.18, 0.24, 0.19, 0.26)
    trails = (2.6, 3.0, 2.4, 3.4, 2.8, 3.6)
    out = []
    for pair in range(3):
        for s_i, s in enumerate((-1.0, 1.0)):
            i = pair * 2 + s_i
            # Body frame carries the fuselage axis and the two wings. The drop
            # is applied in WORLD -Z on purpose: the airframe is in a 27 deg
            # dive here, so rotating a body -Z offset would actually lift the
            # mount above the aircraft instead of putting it underneath.
            # Three evenly spaced stations aft along the heading axis, mirrored
            # left/right. The spacing has to be visible at 3 km (~1.8 px/m):
            # 6/13/20 m gives two readable columns instead of one white blob.
            off_body = np.array([-(6.0 + 7.0 * pair),
                                 s * (5.0 + 1.5 * pair), 0.0], float)
            pos = p0 + R @ off_body
            pos[2] -= (2.0 + 0.8 * pair)
            vel = R @ np.array([-6.0, s * 3.0, 0.0], float)
            vel[2] = -(42.0 + 4.0 * pair)   # gravity-led downward dispense
            out.append(dict(
                id="flare_%02d" % (i + 1),
                kind="infrared_flare",
                pos=[round(float(v), 4) for v in pos],
                vel=[round(float(v), 4) for v in vel],
                radius_m=radii[i],
                trail_m=trails[i],
                temp_c=2000,
                decay_s=3,
                band="Ku",
                life=dict(start_s=0),
                note=("dispensed downwards from %s body frame, station %d, side %+d; "
                      "pellet + short streak, no sphere" % (name, pair, int(s)))))
    return out


def build_cfg(dom):
    cfg = copy.deepcopy(jload(os.path.join(SCENES, dom["base"])))
    cfg["frames"]["n"] = N_FRAMES
    cfg["frames"]["dt"] = 0.1
    cfg["clip"]["frames_per_clip"] = N_FRAMES
    cfg["capture"]["frames"] = N_FRAMES
    cfg["capture"]["sensors"] = SENSORS.split(",")
    contract = cfg.setdefault("__trimodal_contract", {})
    contract["frames"] = N_FRAMES
    contract["modalities"] = ["optical", "ir_lwir", "radar"]
    # Priority-list fixes are on by default via realism.apply; opt into the
    # main-process JPEG product here (Blender's Python has no Pillow).
    cfg["realism"] = dict(enabled=True, jpeg=True)
    cfg["name"] = "ds1109_" + dom["key"]

    if dom["key"] == "ground_vehicle":
        primary = cfg["objects"][0]
        ground_kin = copy.deepcopy(primary.get("kinematics") or dict(
            min_speed_mps=0.0, max_speed_mps=25.0, max_accel_mps2=5.0,
            max_climb_mps=1.0, min_altitude_m=0.0, max_bank_deg=5.0))
        objs = [primary]
        for name, model, pos, yaw, height, mat in STATIC_OBSTACLES:
            objs.append(dict(
                name=name, cls="scenery", shape="obj", model=model,
                pos=list(pos), vel=[0.0, 0.0, 0.0], rot=yaw,
                height=height, mat=mat, label=False,
                motion_type="ground", yaw_mode="fixed",
                note="STATIC obstacle: fixed in world space, must never move"))
        for name, model, pos, vel, height, mat in MOVING_VEHICLES:
            objs.append(dict(
                name=name, cls="scenery", shape="obj", model=model,
                pos=list(pos), vel=list(vel), rot=0.0,
                height=height, mat=mat, label=False,
                motion_type="ground", yaw_mode="velocity",
                kinematics=copy.deepcopy(ground_kin),
                note="MOVING traffic interference: the only ground decoys with motion"))
        cfg["objects"] = objs
        cfg["_why_vehicle_clutter"] = (
            "static obstacles (barrier/fence/shrub/parked car) are pinned with "
            "motion_type=ground and zero velocity; only moving_suv / moving_pickup "
            "have a velocity. Without motion_type the seeker planner silently "
            "turns every object into a formation member that follows the target.")
    elif dom["key"] == "air_plane":
        ecm = cfg.setdefault("ecm", {})
        keep = [e for e in ecm.get("entities", [])
                if e.get("kind") != "infrared_flare"]
        for e in keep:
            if e.get("kind") == "chaff_cloud":
                e["radius_m"] = 2.0   # keep every decoy smaller than the aircraft
        ecm["entities"] = keep + flare_fan(cfg)
        ecm["enabled"] = True
        cfg["_why_flare_fan"] = (
            "six pellets mounted in the aircraft body frame (three symmetric "
            "stations along the fuselage axis) and dispensed downward at "
            "-42..-50 m/s; they do not inherit the aircraft velocity. Head "
            "radius 0.18-0.26 m and trail 2.4-3.6 m keep each round far smaller "
            "than the ~17 m aircraft.")

    # Blender resolves a relative sky_image / ground.backdrop against its OWN
    # cwd, not the scene directory, and silently skips a plate it cannot find.
    # The shipped scenes store relative paths; the v3 builder made them absolute
    # before rendering. Do the same here or the whole real-photo background
    # disappears and the frame degrades to a flat blue field.
    for holder, key in ((cfg.get("optical") or {}, "sky_image"),
                        (cfg.get("ir") or {}, "background_image"),
                        (cfg.get("ground") or {}, "backdrop")):
        p = holder.get(key)
        if isinstance(p, str) and p and not os.path.isabs(p):
            holder[key] = os.path.normpath(os.path.join(SCENES, p))
    return cfg


def run_gen(scene_path, out_dir, threads):
    cmd = [PY, "-m", "simkit", "gen", "-c", scene_path, "-o", out_dir,
           "-n", str(N_FRAMES), "-s", SENSORS]
    env = dict(os.environ)
    env["PYTHONPATH"] = ROOT
    if threads:
        env["SIMKIT_BLENDER_THREADS"] = str(threads)
    print("RUN", " ".join(cmd), flush=True)
    p = subprocess.run(cmd, cwd=ROOT, env=env, capture_output=True,
                       text=True, encoding="utf-8", errors="replace")
    tail = ((p.stdout or "") + "\n" + (p.stderr or ""))[-4000:]
    if p.returncode != 0:
        raise RuntimeError("simkit gen failed (%s):\n%s" % (p.returncode, tail))
    print(tail[-1200:], flush=True)


def count_png(path):
    if not os.path.isdir(path):
        return 0
    return len([n for n in os.listdir(path) if n.lower().endswith(".png")])


def stamp_optical_meta(dest):
    """Idempotently put pHYs + tEXt on every delivered optical PNG.

    PLAN.md §5 item 3. The renderer now stamps these itself, but a run started
    before that change (or a frame written on a path without the geometry pass)
    would otherwise ship bare PNGs. Re-stamping from the saved pixels keeps all
    three domains identical and costs no Cycles render.

    All values are deterministic: FOV from the scene contract, range from
    frames.json, bit depth/colour type from the writer itself. No timestamps,
    paths, seeds or run ids -- that is what keeps repeated runs byte-identical.
    """
    import numpy as np
    from PIL import Image
    sys.path.insert(0, ROOT)
    from simkit import png as png_writer

    stamped = 0
    for dom in DOMAINS:
        cfg_path = os.path.join(SCENES, "ds1109_" + dom["key"] + ".json")
        if not os.path.isfile(cfg_path):
            continue
        view = ((jload(cfg_path).get("__trimodal_contract") or {}).get("view") or {})
        fov = float(view.get("fov_deg") or 8.0)
        run = os.path.join(dest, dom["key"])
        folder = os.path.join(run, "images", "optical")
        if not os.path.isdir(folder):
            continue
        fr_path = os.path.join(run, "frames.json")
        frames = jload(fr_path) if os.path.isfile(fr_path) else []
        for i, fn in enumerate(sorted(n for n in os.listdir(folder)
                                      if n.lower().endswith(".png"))):
            path = os.path.join(folder, fn)
            arr = np.asarray(Image.open(path).convert("RGB"), dtype=np.uint8)
            h, w = arr.shape[:2]
            meta = dict(modality="optical", fov_deg=fov,
                        radiometric_calibration="relative-linear; not absolute")
            if i < len(frames):
                rng = (frames[i] or {}).get("range_m")
                if rng:
                    rng = float(rng)
                    meta["range_m"] = round(rng, 3)
                    meta["gsd_m_per_px"] = round(
                        2.0 * rng * math.tan(math.radians(fov) / 2.0) / w, 6)
            png_writer.write_rgb8(path, arr, meta=meta)
            stamped += 1
    print("META stamped optical PNGs:", stamped)
    return stamped


def verify(dest):
    """Per-domain frame count, modality products and annotation sanity."""
    print("\n=== VERIFY ===")
    ok = True
    report = {}
    for dom in DOMAINS:
        run = os.path.join(dest, dom["key"])
        d = dict(
            optical=count_png(os.path.join(run, "images", "optical")),
            ir_lwir=count_png(os.path.join(run, "images", "ir_lwir")),
            ir_preview=count_png(os.path.join(run, "images", "ir_preview_lwir")),
            radar_rd=count_png(os.path.join(run, "images", "radar")),
            radar_clean=count_png(os.path.join(run, "images", "radar_clean")),
            radar_ra=count_png(os.path.join(run, "images", "radar_ra")),
            jpeg=len([n for n in os.listdir(os.path.join(run, "images", "optical"))
                      if n.lower().endswith(".jpg")])
            if os.path.isdir(os.path.join(run, "images", "optical")) else 0,
        )
        raw = os.path.join(run, "raw", "radar")
        d["radar_npy"] = len([n for n in os.listdir(raw) if n.endswith(".npy")]) \
            if os.path.isdir(raw) else 0
        fr = os.path.join(run, "frames.json")
        d["frames"] = len(jload(fr)) if os.path.isfile(fr) else 0
        coco = os.path.join(run, "annotations_ir_lwir_coco.json")
        c = jload(coco) if os.path.isfile(coco) else {}
        d["coco_images"] = len(c.get("images") or [])
        d["coco_anns"] = len(c.get("annotations") or [])
        meta = jload(os.path.join(run, "meta.json")) if os.path.isfile(
            os.path.join(run, "meta.json")) else {}
        d["meta_frames"] = meta.get("frames")
        d["meta_sensors"] = meta.get("sensors")
        # Every modality must have exactly N_FRAMES products.
        good = all(d[k] == N_FRAMES for k in
                   ("optical", "ir_lwir", "radar_rd", "radar_npy", "frames",
                    "coco_images")) and d["jpeg"] == N_FRAMES
        d["passed"] = bool(good)
        ok = ok and good
        report[dom["key"]] = d
        print("[%s] %-16s %s" % ("PASS" if good else "FAIL", dom["key"], d))
    jwrite(os.path.join(dest, "generation_report.json"),
           dict(dest=dest, frames_per_domain=N_FRAMES, modalities=3,
                domains=report, passed=bool(ok)))
    return ok


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dest", default=DEFAULT_DEST)
    ap.add_argument("--threads", type=int, default=6)
    ap.add_argument("--skip-gen", action="store_true")
    ap.add_argument("--force", action="store_true",
                    help="remove an existing destination before generating")
    args = ap.parse_args()
    dest = os.path.abspath(args.dest)
    os.makedirs(dest, exist_ok=True)

    cfg_paths = {}
    for dom in DOMAINS:
        cfg = build_cfg(dom)
        p = os.path.join(SCENES, "ds1109_" + dom["key"] + ".json")
        jwrite(p, cfg)
        cfg_paths[dom["key"]] = p
        print("CFG", p, "objects", len(cfg.get("objects") or []),
              "ecm", len(((cfg.get("ecm") or {}).get("entities") or [])))

    if not args.skip_gen:
        if args.force:
            for dom in DOMAINS:
                run = os.path.join(dest, dom["key"])
                if os.path.isdir(run):
                    shutil.rmtree(run)
        for dom in DOMAINS:
            run_gen(cfg_paths[dom["key"]],
                    os.path.join(dest, dom["key"]), args.threads)

    stamp_optical_meta(dest)
    good = verify(dest)
    # A short human-readable index next to the data.
    with open(os.path.join(dest, "README.md"), "w", encoding="utf-8") as fh:
        fh.write("# 海 / 陆 / 空 三模态数据集（2026-11-09）\n\n"
                 "每个域 3 帧，每帧三模态：可见光 optical / 长波红外 LWIR / "
                 "毫米波雷达距离-多普勒 RD。由 simkit 离线仿真生成，不含实拍目标。\n\n"
                 "| 目录 | 域 | 帧数 | 干扰 |\n|---|---|---|---|\n"
                 "| air_plane | 空 | 3 | 有源压制 + 假目标 + 箔条云 + 6 枚抛洒式红外诱饵（亮点+拖尾） |\n"
                 "| ground_vehicle | 陆 | 3 | 3 辆真实车辆实例作为硬负样本 + 地杂波 |\n"
                 "| sea_ship | 海 | 3 | 海杂波零多普勒脊 |\n\n"
                 "复现：`env\\Scripts\\python.exe tools\\build_sealandair_1109.py --force`\n")
    print("\nOVERALL", "PASS" if good else "FAIL", "->", dest)
    return 0 if good else 2


if __name__ == "__main__":
    sys.exit(main())
